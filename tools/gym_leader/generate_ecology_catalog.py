#!/usr/bin/env python3
"""Freeze canonical/regional placement roots for the ordinary world ecology."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
rows=json.loads((root/'docs/gym-leader-edition/species-candidate-inventory.json').read_text())['species']
items=sorted({s for row in rows for s in row['placement_directory']})
assert len(items)==973
(root/'src/data/gym_leader_ecology.h').write_text('/* Generated by tools/gym_leader/generate_ecology_catalog.py.\n * Runtime excludes special species, reservations and strength above current rank. */\nstatic const u16 sEcologySpecies[] = {\n'+''.join('    '+s+',\n' for s in items)+'};\n')
print(len(items),'canonical/regional ecology roots')
