#!/usr/bin/env python3
"""Native trainer identities and original overworld locations; no invented cast."""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
ids=set(re.findall(r'^#define (TRAINER_[A-Z0-9_]+)\s+\d+', (ROOT/'include/constants/opponents_frlg.h').read_text(),re.M))
rows={};maximum=0
for p in sorted((ROOT/'data/maps').glob('*_Frlg/map.json')):
 script=p.with_name('scripts.inc')
 if not script.exists():continue
 text=script.read_text();parts=re.split(r'^([A-Za-z0-9_]+)::?\s*\n',text,flags=re.M)
 blocks={parts[i]:parts[i+1] for i in range(1,len(parts)-1,2)}
 data=json.loads(p.read_text())
 for index,obj in enumerate(data['object_events'],1):
  match=re.search(r'trainerbattle(?:_[a-z_]+)?[^\n]*?\b(TRAINER_(?!BATTLE_|TYPE_)[A-Z0-9_]+)',blocks.get(obj.get('script',''),''))
  if not match or match[1] not in ids:continue
  trainer=match[1]
  if trainer in rows:continue
  assert index<200 and obj['x']<256 and obj['y']<256
  rows[trainer]=(data['id'],obj['graphics_id'],index,obj['x'],obj['y'])
  maximum=max(maximum,len(data['object_events']))
assert 'TRAINER_BUG_CATCHER_RICK' in rows
# Personal-bond claims use these append-only source indices. Existing trainer
# order survives new maps, moved NPCs and regeneration; missing entries remain
# reserved so a later source can never inherit an old trainer's reward bit.
output=ROOT/'src/data/gym_leader_recruit_sources.h'
old={}
if output.exists():
 for row in re.findall(r'\{(TRAINER_[A-Z0-9_]+),(MAP_[A-Z0-9_]+),(OBJ_EVENT_GFX_[A-Z0-9_]+),(\d+),(\d+),(\d+)\}',output.read_text()):
  old[row[0]]=(row[1],row[2],int(row[3]),int(row[4]),int(row[5]))
order=list(old)+[trainer for trainer in rows if trainer not in old]
assert len(order)<=256, 'Personal-bond save ledger requires an explicit expansion'
ordered={trainer:rows.get(trainer,old.get(trainer)) for trainer in order}
out=['/* Generated by tools/gym_leader/generate_recruit_sources.py; indices are append-only. */' ,'static const struct GleRecruitSource sRecruitSources[] = {']
for trainer,(map_id,gfx,local_id,x,y) in ordered.items():out.append(f'    {{{trainer},{map_id},{gfx},{local_id},{x},{y}}},')
out.append('};\n');(ROOT/'src/data/gym_leader_recruit_sources.h').write_text('\n'.join(out))
print(len(rows),'native trainer identities; maximum source-map object count',maximum)
