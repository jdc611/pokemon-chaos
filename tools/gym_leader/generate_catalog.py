#!/usr/bin/env python3
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
rows=json.load(open(ROOT/'docs/gym-leader-edition/current-type-exclusive-allocations.json'))
custom=json.load(open(ROOT/'docs/gym-leader-edition/custom-form-runtime-data.json'))
lookup={}
for x in custom:
 key=x['constant'].replace('SPECIES_GLE_','').replace('_',' ').title()
 lookup[key]=x['constant']
lookup.update({'Eternal Hero Palafin':'SPECIES_GLE_ETERNAL_HERO_PALAFIN','Celebi':'SPECIES_GLE_GUARDIAN_CELEBI'})
lookup['Bloodmoon Ursaluna']='SPECIES_URSALUNA_BLOODMOON'
lookup.update({'Urshifu (Rapid Strike)':'SPECIES_URSHIFU_RAPID_STRIKE','Zygarde':'SPECIES_ZYGARDE_50','Zamazenta':'SPECIES_ZAMAZENTA_HERO','Zacian':'SPECIES_ZACIAN_HERO','Meloetta':'SPECIES_MELOETTA_ARIA','Terapagos':'SPECIES_TERAPAGOS_NORMAL'})
constants=(ROOT/'include/constants/species.h').read_text()
types=list(dict.fromkeys(r['gym_type'] for r in rows))
text='/* Generated by tools/gym_leader/generate_catalog.py. */\nstatic const u8 sGleTypes[18] = { '+', '.join('TYPE_'+t.upper() for t in types)+' };\nstatic const u16 sGleExclusive[18][4] = {\n'
flat=[]
for ty in types:
 species=[]
 for r in rows:
  if r['gym_type']!=ty:continue
  n=r['species_or_form'];const=lookup.get(n,'SPECIES_'+re.sub(r'[^A-Z0-9]+','_',n.upper()).strip('_'))
  if not re.search(r'\b'+const+r'\b',constants):
   # Some base forms use the plain species identifier.
   base=const.replace('_HERO','').replace('_NORMAL','')
   assert re.search(r'\b'+base+r'\b',constants),(n,const)
   const=base
  species.append(const);flat.append(const)
 text+='    { '+', '.join(species)+' }, // '+ty+'\n'
text+='};\n'
assert len(flat)==len(set(flat))==72
research=json.load(open(ROOT/'docs/gym-leader-edition/historical-recovery/data/legendary-research-quests.json'))
# Acquisition groups reserved independently from exclusive map slots.
groups=[['TYPE_NULL','SILVALLY'],['REGIROCK','REGICE','REGISTEEL','REGIELEKI','REGIDRAGO','REGIGIGAS'],['TORNADUS','THUNDURUS','LANDORUS','ENAMORUS'],['COBALION','TERRAKION','VIRIZION','KELDEO'],['WO_CHIEN','CHIEN_PAO','TING_LU','CHI_YU'],['UXIE','MESPRIT','AZELF'],['TAPU_KOKO','TAPU_LELE','TAPU_BULU','TAPU_FINI'],['RAIKOU','ENTEI','SUICUNE','RAGING_BOLT','GOUGING_FIRE','WALKING_WAKE'],['ARTICUNO','ZAPDOS','MOLTRES','ARTICUNO_GALAR','ZAPDOS_GALAR','MOLTRES_GALAR'],['OKIDOGI','MUNKIDORI','FEZANDIPITI'],['CYCLIZAR','KORAIDON','MIRAIDON'],['DIALGA','PALKIA','GIRATINA'],['ZARUDE'],['SHAYMIN']]
reserved=[]
for group in groups:
 for n in group:
  c='SPECIES_'+n
  alternatives=[c,c+'_INCARNATE',c+'_ORDINARY',c+'_ORIGIN',c+'_LAND']
  c=next((x for x in alternatives if re.search(r'\b'+x+r'\b',constants)),None)
  assert c,n
  reserved.append(c)
assert not set(flat)&set(reserved),set(flat)&set(reserved)
text+='static const u16 sGleResearchSpecies[] = { '+', '.join(reserved)+' };\n'
(ROOT/'src/data/gym_leader_catalog.h').write_text(text)
print('Catalog: 72 unique exclusive forms,',len(reserved),'research reservations; zero overlaps')
